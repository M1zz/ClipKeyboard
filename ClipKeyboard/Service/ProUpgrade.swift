//  **업그레이드 값** - 칸에 낸 돈을 평생 값에서 빼 준다.
//
//  왜 필요한가: 칸 추가를 산 사람이 그 다음에 평생을 사려면 **두 번 내는 기분**이 된다.
//  그러면 작은 상품이 큰 상품을 막는다. 소액 결제의 진짜 값은 매출이 아니라
//  "이 사람이 결제 버튼을 한 번 눌러 봤다" 는 사실인데, 그 사실이 다음 결제를 가로막으면
//  아무것도 아닌 것이 된다.
//
//  ⚠️ StoreKit 은 비소모성 상품에 할인을 걸 수단이 없다. 반값을 별도 상품으로 만든 것과
//     같은 이유로, 업그레이드도 **별도 SKU** 로만 만들 수 있다.
//
//  ⚠️ 값은 정가에서 칸값을 뺀 자리에 두되, **칸을 먼저 사는 쪽이 더 싸지지 않게** 한다.
//     칸 + 업그레이드가 정가보다 싸지면 정가는 아무 뜻이 없어지고, 모두가 칸부터 산다.
//     (정가 $9.99 · 칸 $2.99 · 업그레이드 $7.99 = 합계 $10.98)
//
//  ⚠️ 이 상품은 **Pro 다.** `ClipKeyboardSpec.entitlementIDs` 에 반드시 들어가야 한다.
//     빠지면 돈을 받고 아무것도 안 열어 주는 상품이 된다.
//

import Foundation

enum ProUpgrade {

    /// 업그레이드 상품 ID.
    /// ⚠️ App Store Connect 에 **비소모성**으로 등록한다. 변경 금지(영수증과의 계약).
    static let productID = "com.Ysoup.TokenMemo.pro.upgrade"

    /// 이 사람에게 업그레이드 값을 보여 줄 것인가.
    ///
    /// 조건은 둘뿐이다: 칸을 샀고, 아직 Pro 가 아니다.
    /// ⚠️ 칸을 안 산 사람에게는 **존재 자체를 알리지 않는다.** 싼 값이 보이면
    ///    정가를 낼 사람이 기다리기 시작한다.
    static var isEligible: Bool {
        SlotPack.isPurchased && !ProFeatureManager.hasPermanentPro
    }
}
